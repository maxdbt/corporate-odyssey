// Logical coordinates stay 800x450; the canvas is rendered RENDER_SCALE times larger (integer, 2..3)
// and every camera zooms by it, so text and pixel art stay sharp on big / high-DPI screens.
export const RENDER_SCALE = (() => {
  if (typeof window === 'undefined') return 2;
  const fit = Math.min(window.innerWidth / GAME_WIDTH, window.innerHeight / GAME_HEIGHT) * (window.devicePixelRatio || 1);
  return Math.max(2, Math.min(3, Math.round(fit)));
})();

